import type { Fragrance } from "./types";

/**
 * Hand-written catalogue, bundled with the app (works offline and on first
 * launch). Source of truth: /catalogue/data/*.json.
 *
 * Entries are short, written for this project and limited to widely published
 * facts. Nothing is scraped from Fragrantica, Parfumo or any other proprietary
 * database. To add fragrances, append to a JSON file and run `npm run catalogue`
 * to validate. See catalogue/README.md.
 */
const modules = import.meta.glob<Fragrance[]>("../../catalogue/data/*.json", {
  eager: true,
  import: "default",
});

export const CATALOGUE: Fragrance[] = Object.keys(modules)
  .sort()
  .flatMap((path) => modules[path]!);

export const CATALOGUE_BY_ID = new Map(CATALOGUE.map((f) => [f.id, f]));

/**
 * Large imported datasets (see catalogue/imported, generated by
 * scripts/import-*.mjs). They are separate lazy chunks so the first page load
 * stays small; the service worker caches them for offline use.
 */
const importedModules = import.meta.glob<Fragrance[]>("../../catalogue/imported/[!_]*.json", {
  import: "default",
});

export async function loadImportedCatalogue(): Promise<Fragrance[]> {
  const parts = await Promise.all(
    Object.keys(importedModules)
      .sort()
      .map((path) => importedModules[path]!()),
  );
  return parts.flat();
}
